"""Generate every release-note format from desktop/changelog.json."""
import html
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def load_changelog(config, root=ROOT):
    entries = json.loads((root / "desktop/changelog.json").read_text(encoding="utf-8"))
    if not isinstance(entries, list) or not entries:
        raise ValueError("Add release notes to desktop/changelog.json before building")
    previous = None
    for entry in entries:
        version = entry.get("version", "")
        if not re.fullmatch(r"\d+\.\d+\.\d+", version):
            raise ValueError("Changelog versions must be major.minor.patch")
        number = tuple(map(int, version.split(".")))
        if previous is not None and number >= previous:
            raise ValueError("Changelog entries must be unique and newest first")
        previous = number
        changes = entry.get("changes")
        if not isinstance(changes, list) or not changes or any(not isinstance(change, str) or not change.strip() for change in changes):
            raise ValueError("Each changelog entry needs non-empty changes")
    if entries[0]["version"] != config["version"]:
        raise ValueError("The newest changelog version must match desktop/release.json")
    return entries


def html_notes(entry):
    return "<h2>Scenic " + html.escape(entry["version"]) + "</h2>\n<ul>\n" + "".join(
        "  <li>" + html.escape(change) + "</li>\n" for change in entry["changes"]
    ) + "</ul>\n"


def text_notes(entry):
    return "Scenic " + entry["version"] + "\n\n" + "\n".join("- " + change for change in entry["changes"]) + "\n"


def prepare_release_notes(config, root=ROOT):
    entries = load_changelog(config, root)
    notes = root / "desktop/release-notes.html"
    notes.write_text(html_notes(entries[0]), encoding="utf-8")
    (root / "desktop/release-notes.txt").write_text(text_notes(entries[0]), encoding="utf-8")
    # Escape '<' so a change cannot become an HTML/script boundary if embedded.
    data = json.dumps({"version": config["version"], "entries": entries}, ensure_ascii=True, indent=2).replace("<", "\\u003c")
    (root / "dist/changelog.js").write_text("// Generated by tools/release_notes.py. Edit desktop/changelog.json.\nwindow.ScenicChangelog = " + data + ";\n", encoding="utf-8")
    return notes


if __name__ == "__main__":
    prepare_release_notes(json.loads((ROOT / "desktop/release.json").read_text(encoding="utf-8")))
